// Static server at DOJO_ORIGIN (default :8765), Chromium CDP at CDP_PORT.
import assert from 'node:assert/strict';
import { writeFileSync, readFileSync, mkdtempSync, existsSync } from 'node:fs';
import { connect, newPage } from './cdp.mjs';
const cdp = await connect();
const page = await newPage(cdp);
const base = process.env.DOJO_ORIGIN || 'http://127.0.0.1:8765';
const route = '/design/iterations/07-heliosdojofeynman.html';
const evaluate = page.evaluate;
const settle = () => evaluate('new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r)))');
const click = async id => { await evaluate(`document.getElementById(${JSON.stringify(id)}).click()`); await settle(); };
const value = async (id, value) => { await evaluate(`{const el=document.getElementById(${JSON.stringify(id)}); el.value=${JSON.stringify(value)}; el.dispatchEvent(new Event('input',{bubbles:true}));}`); await settle(); };
const text = id => evaluate(`document.getElementById(${JSON.stringify(id)}).textContent`);
const screenshot = async name => { const shot = await page.s('Page.captureScreenshot', { format: 'png' }); writeFileSync(`/tmp/heliosdojo-${name}.png`, Buffer.from(shot.data, 'base64')); };
try {
  await page.s('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1100, deviceScaleFactor: 1, mobile: false });
  await page.goto(base + route, 1200);
  await evaluate('localStorage.removeItem("paperland.heliosdojofeynman.v1"); localStorage.setItem("@my.turtle", "existing turtle work");');
  await page.goto(base + route + '#playground');
  assert.match(await text('drawing-count'), /^2 lines/);
  assert.equal(await evaluate('document.getElementById("lab-error").hidden'), true);
  assert.equal(page.requests.filter(url => /^https?:/.test(url) && !url.startsWith(base)).length, 0, 'No remote dependency requests');
  await click('square-example');
  assert.match(await text('drawing-description'), /returns to the beginning/);
  assert.equal(await evaluate('document.querySelectorAll("#pieces button").length'), 8);
  await click('undo-piece');
  assert.equal(await evaluate('document.querySelectorAll("#pieces button").length'), 7);
  await evaluate('document.querySelector("#pieces button").click()');
  await settle();
  assert.equal(await evaluate('document.querySelectorAll("#pieces button").length'), 6);
  await click('tab-play');
  await click('keep-ghost');
  await value('turn', '80');
  assert.match(await text('drawing-description'), /ends .* units/);
  assert.match(await text('drawing-description'), /dashed path/);
  await click('closing-turn');
  assert.match(await text('drawing-description'), /returns to the beginning/);
  await value('sides', '8');
  assert.match(await text('experiment-reading'), /720°/);
  assert.match(await text('experiment-reading'), /comes home/);
  await value('sides', '6');
  await click('closing-turn');
  await value('prediction', 'It will close.');
  await click('tab-create');
  assert.match(await evaluate('document.getElementById("source").value'), /draw thought do\n  for 6 do/);
  assert.match(await text('drawing-count'), /^72 lines/);
  await click('explain-rule');
  assert.match(await text('rule-words'), /6 lines/);
  await value('explanation', 'Repeat a hexagon, turning a little each time.');
  const downloadDir = mkdtempSync('/tmp/heliosdojo-exports-');
  await cdp.send('Browser.setDownloadBehavior', { behavior: 'allow', downloadPath: downloadDir });
  await click('download-code');
  await click('save-image');
  for (let i = 0; i < 50 && (!existsSync(downloadDir + '/my-paperland-study.txt') || !existsSync(downloadDir + '/my-paperland-study.png')); i++) await new Promise(resolve => setTimeout(resolve, 100));
  assert.match(readFileSync(downloadDir + '/my-paperland-study.txt', 'utf8'), /# Repeat a hexagon[\s\S]*draw thought do/);
  assert.equal(readFileSync(downloadDir + '/my-paperland-study.png').subarray(1, 4).toString(), 'PNG');
  await screenshot('desktop');

  const engine = await evaluate(String.raw`(async () => {
    const {compileDrawing, validateProgram} = await import('./07-turtle-engine.js');
    const square = compileDrawing('for 4 do\nfw 40\nrt 90\nend');
    const fraction = compileDrawing('for 6 do\nfw 30\nrt 360/6\nend');
    const bad = ['for 1000000000 do\nend', 'for 360 do\nfor 360 do\nend\nend', 'draw thought do\nthought\nend\nthought', 'fw Infinity', 'fw 1/0', 'fw 10\nend', 'draw constructor do\nfw 1\nend', 'for 2 do\nfw 2'];
    return {square: square.gap, fraction: fraction.gap, rejected: bad.map(s => {try {validateProgram(s); return false;} catch {return true;}})};
  })()`);
  assert.ok(engine.square < .001 && engine.fraction < .001);
  assert.ok(engine.rejected.every(Boolean), 'Bounded execution rejects recursive, huge, malformed programs');
  const before = await evaluate('document.getElementById("dojo-canvas").toDataURL()');
  await value('source', 'for 999999999 do\nend');
  await click('run-code');
  assert.equal(await evaluate('document.getElementById("lab-error").hidden'), false);
  assert.equal(await evaluate('document.getElementById("dojo-canvas").toDataURL()'), before, 'Invalid code retains last drawing');
  await value('source', 'beColour coral\nfor 3 do\nfw 30\nrt 120\nend');
  await click('run-code');
  assert.match(await text('drawing-count'), /^3 lines/);
  await click('restore-rule');
  await evaluate('document.getElementById("tab-create").focus()');
  await page.s('Input.dispatchKeyEvent', { type: 'keyDown', key: 'ArrowLeft', code: 'ArrowLeft' });
  assert.equal(await evaluate('document.activeElement.id'), 'tab-play');
  await click('tab-create');
  for (const width of [320, 390, 768]) {
    await page.s('Emulation.setDeviceMetricsOverride', { width, height: 844, deviceScaleFactor: 1, mobile: false });
    await evaluate('document.getElementById("copies").scrollIntoView({behavior:"instant",block:"center"})');
    await settle();
    assert.ok(await evaluate('document.documentElement.scrollWidth <= innerWidth'), `No overflow at ${width}px`);
    assert.ok(await evaluate('document.getElementById("dojo-canvas").getBoundingClientRect().top < 20'), 'Mobile preview remains visible beside controls');
    if (width === 390) await screenshot('mobile');
  }
  await page.s('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] });
  await settle(); await click('replay');
  assert.equal(await text('replay'), '↻ Trace the rule');
  await page.goto(base + route + '#playground');
  assert.equal(await evaluate('document.getElementById("explanation").value'), 'Repeat a hexagon, turning a little each time.');
  assert.equal(await evaluate('localStorage.getItem("@my.turtle")'), 'existing turtle work');

  await click('offline-save');
  await evaluate(`new Promise((resolve,reject) => { const start=Date.now(); const timer=setInterval(() => { if(!document.getElementById('offline-save').disabled) {clearInterval(timer);resolve();} else if(Date.now()-start>25000){clearInterval(timer);reject(Error('Offline install timeout'));}},100);})`);
  assert.match(await text('offline-status'), /Saved for offline reloads/);
  // Reload under the activated worker before testing a cold, offline navigation.
  await page.goto(base + route);
  assert.equal(await evaluate('!!navigator.serviceWorker.controller'), true);
  await page.s('Network.setCacheDisabled', { cacheDisabled: true });
  await page.s('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: 0, uploadThroughput: 0 });
  await page.goto(base + route + '?offline-check=1#playground', 1800);
  assert.match(await text('drawing-count'), /^72 lines/);
  await value('copies', '24');
  assert.match(await text('drawing-count'), /^144 lines/, 'Offline interpreter still runs');
  assert.equal(await evaluate('document.getElementById("lab-error").hidden'), true);
  assert.deepEqual(page.console.filter(item => item.type === 'exception'), [], 'No uncaught exceptions');
  console.log('PASS: actual turtle geometry; three stages; chips; ghost comparison; custom code/error recovery; bounded execution; keyboard; local persistence; untouched /turtle draft; 320/390/768px layouts; reduced motion; zero remote dependencies; offline reload and interaction.');
  console.log('Screenshots: /tmp/heliosdojo-{desktop,mobile}.png');
} finally { cdp.close(); }
